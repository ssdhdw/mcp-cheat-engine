"""Package/install the self-contained CE startup bridge without requiring Lua Engine."""
import argparse
import os
from pathlib import Path
import tempfile

MARKER = "-- Cheat Engine MCP autorun; generated by mcp/install_autorun.py\n"
FILENAME = "ce_mcp.lua"
PACKAGED = Path(__file__).resolve().parents[1] / "Cheat Engine" / "bin" / "autorun" / FILENAME


def render_autorun():
    source = Path(__file__).with_name("ce_bridge.lua").read_text(encoding="utf-8")
    return MARKER + "if ce_mcp then return end\n" + source + "\nce_mcp.start()\n"


def write_owned(path, content):
    if path.exists() and not path.read_text(encoding="utf-8").startswith(MARKER):
        raise ValueError(f"Refusing to overwrite an unrelated script: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                dir=path.parent, prefix=FILENAME + ".", suffix=".tmp", delete=False) as stream:
            temp = Path(stream.name)
            stream.write(content)
        os.replace(temp, path)
    finally:
        if temp is not None:
            temp.unlink(missing_ok=True)


def install(directory, uninstall=False):
    directory = directory.resolve(strict=True)
    if not any((directory / name).is_file() for name in
               ("Cheat Engine.exe", "cheatengine-x86_64.exe", "cheatengine-i386.exe",
                "cheatengine-x86_64-SSE4-AVX2.exe")):
        raise ValueError("Select the Cheat Engine directory containing its executable")
    target = directory / "autorun" / FILENAME
    if uninstall:
        if target.exists():
            if not target.read_text(encoding="utf-8").startswith(MARKER):
                raise ValueError(f"Refusing to remove an unrelated script: {target}")
            target.unlink()
    else:
        write_owned(target, render_autorun())
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ce-dir", type=Path,
        default=Path(os.environ.get("ProgramFiles", "C:/Program Files")) / "Cheat Engine")
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--package", action="store_true", help="Regenerate the fork's bundled autorun")
    args = parser.parse_args()
    if args.package:
        if args.uninstall:
            parser.error("--package cannot be combined with --uninstall")
        write_owned(PACKAGED, render_autorun())
        print(f"Packaged: {PACKAGED}")
    else:
        target = install(args.ce_dir, args.uninstall)
        print(f"{'Removed' if args.uninstall else 'Installed'}: {target}")
        print("Restart Cheat Engine to apply the change.")


if __name__ == "__main__":
    main()
